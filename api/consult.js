export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const OPENAI_API_KEY = process.env.OPENAI_API_KEY;
  if (!OPENAI_API_KEY) {
    return res.status(500).json({ error: 'OpenAI APIキーが設定されていません。' });
  }

  try {
    const { worry, feeling, goal, zodiac, number, history, compatContext } = req.body;

    // ─────────────────────────────────────────────────────
    // STEP 1: worry のキーワードから相談タイプを判定
    // ─────────────────────────────────────────────────────
    function detectType(w) {
      if (!w) return 'general';
      if (/セックス|性行為|えっち|エッチ|スキンシップ|身体的|sm|SM|プレイ|性的|性欲|求め(て|られ)|拒(否|絶|ま)/.test(w)) return 'sexual';
      if (/不倫|浮気|既婚|妻|夫|奥さん|旦那|ダブル|二股|秘密の関係|バレ|隠/.test(w))            return 'affair';
      if (/返信|既読|LINE|ライン|連絡|メッセ|未読|スルー|無視|来ない/.test(w))                  return 'no_reply';
      if (/別れ|別れた|終わり|フラれ|振られ|失恋|元(カレ|カノ|彼)|復縁/.test(w))               return 'breakup';
      if (/告白|片思|気持ち(を伝|が伝わ)|どう思われ|アプローチ/.test(w))                        return 'confession';
      if (/嫉妬|やきもち|独占|他の(女|男|人)|束縛/.test(w))                                     return 'jealousy';
      if (/忘れられ|頭から離れ|執着|引きずっ|忘れ(たい|られない)/.test(w))                      return 'obsession';
      if (/結婚|将来|同棲|プロポーズ|転職|キャリア|進路/.test(w))                               return 'future';
      if (/自信(が|は)(な|持て)|自分が(嫌|ダメ)|自己嫌悪|どうせ私|価値がな/.test(w))            return 'self_denial';
      if (/職場|上司|同僚|パワハラ|モラハラ|人間関係/.test(w))                                  return 'workplace';
      if (/親|母|父|家族|兄弟|義母|義父|子ども|子育て/.test(w))                                 return 'family';
      if (/孤独|一人|ひとり|寂し|誰もいない|わかってくれ|理解されない/.test(w))                 return 'loneliness';
      if (/腹が立|むかつ|イライラ|許せ|ひどい|なんで(して|くれ)/.test(w))                       return 'anger';
      if (/彼|好き|関係|付き合|恋|愛|気持ち/.test(w))                                           return 'romance_general';
      return 'general';
    }

    const worryType = detectType(worry);

    // ─────────────────────────────────────────────────────
    // STEP 2: タイプ別のカウンセリング指示
    // ─────────────────────────────────────────────────────
    const typeInstructions = {

      sexual: `
あなたは性的な悩みにも誠実に向き合うカウンセラーです。
ユーザーは性的欲求・不一致・拒絶に関する悩みを抱えています。
以下を丁寧に読み解いてください：
- 欲求そのものを恥ずかしいものとして扱わず、正直な気持ちとして受け取る
- 「拒否された/応じてもらえない」ことへの傷つき・寂しさ・怒り
- 愛情確認の手段としての性的つながりへの渇望
- 相手との温度差・性的相性への不安
- 怒りの奥にある「もっと求められたい」「大切にされたい」という本音
その上で「少し楽になるために」では：
- 相手を責める形でなく、自分の希望として伝える言葉の選び方
- いきなり要求するのではなく、安心できる会話から近づくアプローチ
- 相手の同意やペースを尊重しながら距離を縮める方法
- それでも相手が応じない場合、価値観・性的相性の違いとして捉え直す視点
道徳的な判断や「控えて」などの言葉は使わない。`,

      affair: `
あなたは不倫・複雑な関係の悩みに偏見なく向き合うカウンセラーです。
良い・悪いの道徳判断をせず、以下を読み解いてください：
- この関係で何を得ていて、何が苦しいのか
- 罪悪感と強い引力の間で揺れている葛藤
- 「終わりにしたい」と「離れられない」が同時に存在していること
- この関係が映し出している、本来の生活や関係性への不満・空白
「やめなさい」「不倫はいけない」などの説教は絶対にしない。
自分の気持ちを整理し、今後の方向性を自分で選べるための視点を示す。`,

      no_reply: `
あなたは返信・連絡の不安に寄り添うカウンセラーです。
以下を読み解いてください：
- 連絡がこない間、頭の中で何度もシナリオを繰り返してきた消耗
- 「嫌われたのか」「何かしたのか」と自分を責め始めていること
- 待つことの消耗と、連絡したいのに踏み出せない葛藤
- 相手の温度と自分の温度のズレが生む不安
「相手には相手の都合がある」という言葉で片付けず、
今の苦しさをまず受け取ってから、関係の温度を確認する具体的な方法を示す。`,

      breakup: `
あなたは別れ・失恋の痛みに向き合うカウンセラーです。
以下を読み解いてください：
- 別れた事実よりも「自分はどこで何を失ったのか」という喪失感
- 後悔・空白感・「なぜこうなったか」を繰り返す思考ループ
- 元に戻りたいのか、この痛みから逃げたいのかの区別
- 今感じている感情が、この先への怖さからきていること
「時間が解決する」などの表面的な慰めは使わない。
今この痛みと付き合いながら、自分を保てる視点を伝える。`,

      confession: `
あなたは告白・好意の伝え方の悩みに向き合うカウンセラーです。
以下を読み解いてください：
- 伝えたい気持ちと、断られることへの恐怖の綱引き
- 「タイミング」「言い方」を考えすぎて動けなくなっている状態
- 伝えることで「今の関係が壊れる」という恐れ
- 伝えないまま積み重なっている焦りと後悔
告白の結果より「自分の気持ちに正直でいること」の価値を伝え、
具体的に踏み出しやすいアプローチを示す。`,

      jealousy: `
あなたは嫉妬・独占欲の悩みに向き合うカウンセラーです。
以下を読み解いてください：
- 嫉妬の奥にある「失いたくない」という切実な気持ち
- 自分への自信のなさが嫉妬を増幅させていること
- 「疑いたくない」のに疑ってしまう自分への嫌悪感
- 独占しようとするほど相手が遠ざかるジレンマ
嫉妬を否定せず、その根にある不安を整理した上で、
相手との信頼を育てるための視点を示す。`,

      obsession: `
あなたは執着・忘れられない悩みに向き合うカウンセラーです。
以下を読み解いてください：
- 「忘れたい」と思っているのに頭から離れない苦しさ
- その人のことを考えることが、今の自分の支えになってしまっていること
- 手放すことへの恐怖（手放したら空っぽになる感覚）
- 執着している相手に投影している「本当に求めているもの」
「忘れよう」と押しつけず、自分の重心を内側に戻すための視点を伝える。`,

      future: `
あなたは将来・結婚・進路の不安に向き合うカウンセラーです。
以下を読み解いてください：
- 「決めなければ」というプレッシャーが選択肢を狭めていること
- 他者の期待と自分の本音のズレへの違和感
- 「正解の人生」を探しているうちに、今が疎かになっていること
- 決められない理由が「怠け」ではなく「大切にしたいものが多い」からであること
今すぐ決断を求めず、自分の価値観を整理して次の一歩が見えるような視点を示す。`,

      self_denial: `
あなたは自己否定・自信のなさに向き合うカウンセラーです。
以下を読み解いてください：
- 「自分はダメだ」という声がどこから来ているか
- 自己否定が長年「努力のモチベーション」として使われてきた疲れ
- 自分を肯定することへの罪悪感（「調子に乗っている」と感じること）
- 完璧でない自分を受け入れることへの恐怖
「自分を好きになれ」という押しつけをせず、
今の場所からそっと息ができる視点を伝える。`,

      workplace: `
あなたは職場・人間関係の疲れに向き合うカウンセラーです。
以下を読み解いてください：
- 消耗しながらも「辞められない」「言えない」理由
- 理不尽さへの怒りと、その怒りを出せない息苦しさ
- 「自分が悪いのか」と思い始めていること
- 職場外での気力が削られていること
逃げることを否定せず、今の環境で境界線を引く方法と、
先を見据えた選択肢の整理を伝える。`,

      family: `
あなたは家族関係の悩みに寄り添うカウンセラーです。
以下を読み解いてください：
- 家族だからこそ言えない・傷つく関係性の矛盾
- 「好きだから」「嫌いだから」では割り切れない複雑な感情
- 距離を置きたいのに「縁を切る」ことへの罪悪感
- 自分が先に変わるしかないという思い込み
家族への怒り・悲しみを「あってはいけない感情」として扱わず、
今の距離感を整えるための視点を示す。`,

      loneliness: `
あなたは孤独・寂しさに向き合うカウンセラーです。
以下を読み解いてください：
- 「一人でいること」と「孤独を感じること」の違い
- 「わかってほしい」相手が特定の誰かなのか、誰でもいいのかの違い
- つながりを求めながら、傷つくのが怖くて動けないこと
- 孤独感の奥にある「自分はつながるに値するのか」という問い
孤独を「解決すべき問題」として扱わず、
今の状態に寄り添いながら小さなつながりへの一歩を示す。`,

      anger: `
あなたは怒り・不満の感情に向き合うカウンセラーです。
以下を読み解いてください：
- 怒りの奥にある「こうあってほしかった」という期待と裏切られた感覚
- 怒りを溜め込んできた消耗
- 怒っている自分を「感情的」と自己嫌悪してしまうこと
- 「許すこと」と「忘れること」は違うこと
怒りを否定せず、そのエネルギーを消耗から行動に変える視点を示す。`,

      romance_general: `
あなたは恋愛の悩みに丁寧に向き合うカウンセラーです。
以下を読み解いてください：
- この関係で感じている手応えと不安の両方
- 「相手の気持ちがわからない」ことへの消耗
- 自分がどう見られているかを気にしすぎていること
- 本当はこの関係に何を求めているか
相手を変えようとする方向ではなく、
自分の気持ちを整理して動きやすくなる視点を示す。`,

      general: `
あなたは何でも話せる、寄り添い型のカウンセラーです。
相談内容を丁寧に読み取り、汎用的な慰めではなく、
この人の言葉に対して正面から応えてください。`
    };

    const typeInstruction = typeInstructions[worryType] || typeInstructions.general;

    // ─────────────────────────────────────────────────────
    // STEP 3: 星座・数秘の補足
    // ─────────────────────────────────────────────────────
    const zodiacNote = (zodiac && number)
      ? `\n星座は${zodiac}、数秘は${number}。これらの特性を押しつけにならない程度に自然に絡めてください。`
      : '';

    // ─────────────────────────────────────────────────────
    // STEP 4: システムプロンプト構築
    // ─────────────────────────────────────────────────────
    const systemInstruction = `
${typeInstruction}${zodiacNote}

【重要な制約】
- 毎回同じ表現（「わからないままでいい」「自分を責めないで」「時間が解決する」など）は使わない
- 相談内容を読んでいることが伝わる、この人だけへの言葉で書く
- 道徳的な説教・「べき」論は避ける
- 感情を否定しない

【出力形式】
必ずJSON形式のみで返すこと。前後に説明文や\`\`\`は一切つけない。
{
  "message": "「今のあなたへ」の本文。相談内容の感情の層を深く読み解く。4〜6段落。",
  "relief": "「少し楽になるために」の本文。goalを踏まえながら今できる具体的な一歩・伝え方・距離感・視点を4〜6段落で。goalだけを答えの中心にしない。",
  "showCompat": true または false。以下の基準で厳密に判定すること。
trueにする条件（相手との関係性そのものがテーマの相談）：
  相手の気持ちを知りたい／なぜ噛み合わないか知りたい／距離感に悩んでいる／
  感情の温度差がある／関係を改善したい／相手との相性が不安／
  好きだけど苦しい／嫌いだけど切れない／関係に消耗している。
falseにする条件（関係性分析が主目的ではない相談）：
  単なる愚痴／口臭・マナー・行動への一時的な不満／
  仕事量・業務上の不満／性格の悪口／
  「その人との関係をどうしたいか」が相談の主題でない場合。
人物が登場するだけで true にしないこと。
「この相談者が相手との関係性・距離感・感情の噛み合わなさを読み解きたいか」を文章全体で判断すること。
}
`.trim();

    // 過去の相談履歴をプロンプトに追加（深掘り時）
    let historyNote = '';
    if (Array.isArray(history) && history.length > 0) {
      historyNote = '\n\n【これまでの相談履歴（文脈として参照してください）】\n';
      history.forEach((h, i) => {
        historyNote += `\n─ 第${i+1}回 ─\n`;
        historyNote += `悩み：${h.worry}\n気持ち：${h.feeling}\n`;
        historyNote += `回答（今のあなたへ）：${h.message}\n`;
        if (h.relief) historyNote += `回答（少し楽になるために）：${h.relief}\n`;
      });
      historyNote += '\n上記の履歴を踏まえ、今回は「その後」として深掘りしてください。前回と同じことを繰り返さず、一歩進んだ視点で答えてください。';
    }

    // 相性診断結果をプロンプトに追加
    let compatNote = '';
    if (compatContext && compatContext.compat) {
      compatNote = `\n\n【相性診断の結果（参照情報）】\n相手との相性：${compatContext.compat}\nすれ違いやすいポイント：${compatContext.gap || ''}\nよりよく関わるために：${compatContext.how || ''}`;
    }

    const promptText = `【相談内容】${worry}\n【今の気持ち】${feeling}\n【どうなりたいか】${goal || '（未入力）'}${compatNote}${historyNote}`;

    // ─────────────────────────────────────────────────────
    // STEP 5: OpenAI API 呼び出し
    // ─────────────────────────────────────────────────────
    const response = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${OPENAI_API_KEY}`
      },
      body: JSON.stringify({
        model: 'gpt-4o-mini',
        messages: [
          { role: 'system', content: systemInstruction },
          { role: 'user',   content: promptText }
        ],
        temperature: 0.75,
        response_format: { type: 'json_object' }
      })
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('OpenAI API Error:', response.status, errorText);
      return res.status(response.status).json({ error: 'Failed to connect to AI', details: errorText });
    }

    const data = await response.json();
    const raw = data.choices?.[0]?.message?.content;
    if (!raw) throw new Error('AIから有効な回答が返ってきませんでした');

    // ─────────────────────────────────────────────────────
    // STEP 6: JSONパース → フロントへ返す
    // ─────────────────────────────────────────────────────
    let parsed;
    try {
      parsed = JSON.parse(raw.replace(/```json|```/g, '').trim());
    } catch (e) {
      // パース失敗時はrawをそのままmessageとして返す
      return res.status(200).json({ message: raw, relief: '', showCompat: false });
    }

    return res.status(200).json({
      message:    parsed.message    || '',
      relief:     parsed.relief     || '',
      showCompat: parsed.showCompat ?? false
    });

  } catch (error) {
    console.error('API Error:', error);
    res.status(500).json({ error: 'Failed to connect to AI' });
  }
}
